import re

import pandas as pd
import streamlit as st


def format_context_with_highlight(text):
    return re.sub(r"<<<([^>]+)>>>", r":red[\1]", text)


def display_contexts_table_simple(contexts):
    if not contexts:
        st.info("Контексты не найдены.")
        return

    contexts_df = pd.DataFrame(contexts).sort_values(by="Год")
    contexts_df.index = range(1, len(contexts_df) + 1)
    st.dataframe(contexts_df, width="stretch")


def display_contexts_table_highlighted(contexts):
    if not contexts:
        st.info("Контексты не найдены.")
        return

    sorted_contexts = sorted(contexts, key=lambda item: item["Год"])
    markdown_table = "| № | Контекст | Произведение | Год |\n"
    markdown_table += "|---|----------|--------------|-----|\n"

    for index, context in enumerate(sorted_contexts, start=1):
        formatted_text = format_context_with_highlight(context["Контекст"]).replace("|", "\\|")
        title_escaped = context["Произведение"].replace("|", "\\|")
        markdown_table += f"| {index} | {formatted_text} | {title_escaped} | {context['Год']} |\n"

    st.markdown(markdown_table)


